async def save_config(request: Request):
    require_write(request)
    payload = await limited_json(request, MAX_CONFIG_BYTES)
    if not all(isinstance(payload.get(name), dict) for name in ("campaign", "content", "vsl", "analytics", "legal")):
        raise HTTPException(400, "Configuração incompleta.")
    number = re.sub(r"\D", "", str(payload["campaign"].get("whatsapp", "")))
    if number and not re.fullmatch(r"\d{12,15}", number):
        raise HTTPException(400, "WhatsApp precisa incluir DDI e DDD.")
    payload["campaign"]["whatsapp"] = number
    with database() as db:
        db.execute("INSERT INTO config(key,value) VALUES('site',?) ON CONFLICT(key) DO UPDATE SET value=excluded.value", (json.dumps(payload, ensure_ascii=False),))
    return {"ok": True}


@app.post("/api/leads")
async def create_lead(request: Request):
    if not same_origin(request):
        raise HTTPException(403, "Origem inválida.")
    if rate_limited(LEAD_ATTEMPTS, client_ip(request), 15, 3600):
        raise HTTPException(429, "Muitas tentativas. Tente mais tarde.")
    payload = await limited_json(request, 16_000)
    instagram = str(payload.get("instagram", "")).strip()
    if not re.fullmatch(r"@[A-Za-z0-9._]{2,30}", instagram):
        raise HTTPException(400, "Instagram inválido.")
    answers = payload.get("answers") if isinstance(payload.get("answers"), dict) else {}
    attribution = payload.get("attribution") if isinstance(payload.get("attribution"), dict) else {}
    device = payload.get("device") if isinstance(payload.get("device"), dict) else {}
    creator_id = uuid.uuid4().hex
    with database() as db:
        db.execute(
            """INSERT INTO creators(id,created_at,source,instagram,followers,stories,experience,attribution_json,device_json)
               VALUES(?,?,?,?,?,?,?,?,?)""",
            (creator_id, now_iso(), "quiz", instagram, str(answers.get("question_1", ""))[:80],
             str(answers.get("question_2", ""))[:80], str(answers.get("question_3", ""))[:80],
             json.dumps(attribution, ensure_ascii=False)[:4000], json.dumps(device, ensure_ascii=False)[:4000]),
        )
    return JSONResponse({"ok": True, "id": creator_id}, status_code=201)


