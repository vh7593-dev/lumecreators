@app.post("/api/setup/start")
async def setup_start(request: Request):
    if not same_origin(request):
        raise HTTPException(403, "Origem inválida.")
    if rate_limited(SETUP_ATTEMPTS, client_ip(request), 8, 1800):
        raise HTTPException(429, "Muitas tentativas. Aguarde alguns minutos.")
    payload = await limited_json(request, 4_000)
    setup_key = str(payload.get("setup_key", ""))[:512]
    require_setup_access(request, setup_key)
    email = str(payload.get("email", "")).strip().lower()[:254]
    display_name = str(payload.get("display_name", "")).strip()[:80]
    password = str(payload.get("password", ""))
    if not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email):
        raise HTTPException(400, "Informe um e-mail válido.")
    if len(display_name) < 2:
        raise HTTPException(400, "Informe seu nome.")
    if len(password) < 8 or len(password) > 512:
        raise HTTPException(400, "A senha precisa ter entre 8 e 512 caracteres.")
    salt = secrets.token_bytes(16)
    with database() as db:
        if DATABASE_URL:
            db.execute("SELECT pg_advisory_xact_lock(687543211)")
        else:
            db.execute("BEGIN IMMEDIATE")
        if db.execute("SELECT 1 FROM admin_users LIMIT 1").fetchone():
            raise HTTPException(409, "O cadastro inicial já foi concluído.")
        cursor = db.execute(
            """INSERT INTO admin_users(email,display_name,password_salt,password_hash,totp_secret)
               VALUES(?,?,?,?,?) RETURNING id""",
            (email, display_name, salt.hex(), password_hash(password, salt), ""),
        )
        return new_session_response(db, cursor.fetchone()["id"])


@app.post("/api/auth/login")
async def login(request: Request):
    if not same_origin(request):
        raise HTTPException(403, "Origem inválida.")
    key = client_ip(request)
    if rate_limited(LOGIN_ATTEMPTS, key, 12, 900):
        raise HTTPException(429, "Muitas tentativas. Tente novamente em alguns minutos.")
    payload = await limited_json(request, 4_000)
    email = str(payload.get("email", "")).strip().lower()[:254]
    password = str(payload.get("password", ""))[:512]
    with database() as db:
        statement = "SELECT * FROM admin_users WHERE email = ?"
        if DATABASE_URL:
            statement += " FOR UPDATE"
        user = db.execute(statement, (email,)).fetchone()
        if not user or user["locked_until"] > int(time.time()):
            raise HTTPException(401, "E-mail ou senha inválidos.")
        expected = password_hash(password, bytes.fromhex(user["password_salt"]))
        if not hmac.compare_digest(expected, user["password_hash"]):
            failures = user["failed_attempts"] + 1
            locked_until = int(time.time()) + 900 if failures >= 5 else 0
            db.execute("UPDATE admin_users SET failed_attempts=?, locked_until=? WHERE id=?", (failures if failures < 5 else 0, locked_until, user["id"]))
            db.commit()
            raise HTTPException(401, "E-mail ou senha inválidos.")
        db.execute("UPDATE admin_users SET failed_attempts=0, locked_until=0 WHERE id=?", (user["id"],))
        return new_session_response(db, user["id"])


