class PostgresDatabase:
    """Keep the existing parameterized SQLite queries usable with Psycopg."""

    def __init__(self, connection):
        self.connection = connection

    def execute(self, statement: str, parameters=()):
        return self.connection.execute(statement.replace("?", "%s"), parameters)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()


@contextmanager
def _raw_database():
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row

        connection = psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10)
        db = PostgresDatabase(connection)
    else:
        if IS_VERCEL:
            raise HTTPException(503, "Configure DATABASE_URL com um PostgreSQL persistente antes de publicar.")
        DATA_DIR.mkdir(parents=True, exist_ok=True)
        connection = sqlite3.connect(DB_PATH, timeout=15)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys = ON")
        connection.execute("PRAGMA journal_mode = WAL")
        db = connection
    try:
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        connection.close()


@contextmanager
def database():
    if not _SCHEMA_READY:
        init_database()
    with _raw_database() as db:
        yield db


