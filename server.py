@app.put("/api/admin/video")
async def upload_video(request: Request):
    require_write(request)
    if IS_VERCEL:
        raise HTTPException(501, "Na Vercel, hospede o MP4 em armazenamento externo e use URL direta no painel.")
    if request.headers.get("content-type", "").split(";", 1)[0] != "video/mp4":
        raise HTTPException(415, "Envie um arquivo MP4.")
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    temporary = DATA_DIR / f"upload-{uuid.uuid4().hex}.tmp"
    size = 0
    try:
        with temporary.open("wb") as output:
            async for chunk in request.stream():
                size += len(chunk)
                if size > MAX_VIDEO_BYTES:
                    raise HTTPException(413, "O MP4 deve ter até 250 MB.")
                output.write(chunk)
        with temporary.open("rb") as uploaded:
            if uploaded.read(12)[4:8] != b"ftyp":
                raise HTTPException(400, "O arquivo não parece ser um MP4 válido.")
        temporary.replace(VIDEO_PATH)
    finally:
        temporary.unlink(missing_ok=True)
    return {"ok": True, "size": size}


@app.get("/media/campaign.mp4")
def campaign_video():
    if VIDEO_URL:
        parsed = urlparse(VIDEO_URL)
        if parsed.scheme != "https" or not parsed.netloc:
            raise HTTPException(503, "LUME_VIDEO_URL precisa ser uma URL HTTPS direta do MP4.")
        return RedirectResponse(VIDEO_URL, status_code=307, headers={"Cache-Control": "public, max-age=300"})
    if IS_VERCEL:
        raise HTTPException(404, "Configure LUME_VIDEO_URL ou uma URL direta de MP4 no painel.")
    if not VIDEO_PATH.is_file():
        raise HTTPException(404)
    return FileResponse(VIDEO_PATH, media_type="video/mp4", headers={"Cache-Control": "public, max-age=3600"})


