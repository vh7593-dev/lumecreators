@app.post("/api/admin/import-leads")
async def import_local_leads(request: Request):
    require_write(request)
    payload = await limited_json(request, MAX_CONFIG_BYTES)
    leads = payload.get("leads")
    if not isinstance(leads, list) or len(leads) > 1000:
        raise HTTPException(400, "Lista inválida.")
    added = 0
    with database() as db:
        for lead in leads:
            if not isinstance(lead, dict):
                continue
            instagram = str(lead.get("instagram", ""))[:32]
            if not re.fullmatch(r"@[A-Za-z0-9._]{2,30}", instagram):
                continue
            answers = lead.get("answers") if isinstance(lead.get("answers"), dict) else {}
            cursor = db.execute(
                """INSERT INTO creators(id,legacy_id,created_at,source,instagram,followers,stories,experience,attribution_json,device_json)
                   VALUES(?,?,?,?,?,?,?,?,?,?) ON CONFLICT DO NOTHING""",
                (uuid.uuid4().hex, str(lead.get("id", ""))[:120] or None, str(lead.get("createdAt", ""))[:40] or now_iso(),
                 "quiz", instagram, str(answers.get("question_1", ""))[:80], str(answers.get("question_2", ""))[:80],
                 str(answers.get("question_3", ""))[:80], json.dumps(lead.get("attribution") or {}, ensure_ascii=False)[:4000],
                 json.dumps(lead.get("device") or {}, ensure_ascii=False)[:4000]),
            )
            added += cursor.rowcount
    return {"ok": True, "added": added}


@app.get("/api/admin/dashboard")
def dashboard(request: Request):
    require_session(request)
    with database() as db:
        row = db.execute(
            """SELECT COUNT(*) AS total,
               SUM(CASE WHEN status IN ('fechado','divulgando','concluido') THEN 1 ELSE 0 END) AS closed,
               SUM(CASE WHEN status='divulgando' THEN 1 ELSE 0 END) AS running,
               SUM(CASE WHEN status='nao_divulgou' THEN 1 ELSE 0 END) AS did_not_post,
               SUM(valid_depositors) AS depositors,
               SUM(revenue_cents) AS revenue_cents,
               SUM(payout_cents) AS payout_cents FROM creators"""
        ).fetchone()
    data = {key: row[key] or 0 for key in row.keys()}
    data["balance_cents"] = data["revenue_cents"] - data["payout_cents"]
    return data


@app.get("/api/admin/export.csv")
def export_csv(request: Request):
    require_session(request)
    with database() as db:
        rows = db.execute("SELECT * FROM creators ORDER BY created_at DESC").fetchall()
    output = io.StringIO()
    writer = csv.writer(output)
    columns = ("created_at", "source", "name", "instagram", "followers", "stories", "experience", "status", "valid_depositors", "revenue_cents", "payout_cents", "notes")
    writer.writerow(columns)
    for row in rows:
        writer.writerow([csv_safe(row[key]) for key in columns])
    return Response("\ufeff" + output.getvalue(), media_type="text/csv; charset=utf-8", headers={"Content-Disposition": 'attachment; filename="lume-creators.csv"'})


def csv_safe(value):
    if isinstance(value, str) and value.lstrip().startswith(("=", "+", "-", "@", "\t", "\r")):
        return "'" + value
    return value


