@app.post("/api/admin/creators")
async def add_creator(request: Request):
    require_write(request)
    payload = await limited_json(request, 8_000)
    instagram = str(payload.get("instagram", "")).strip().lstrip("@")
    if not re.fullmatch(r"[A-Za-z0-9._]{2,30}", instagram):
        raise HTTPException(400, "Informe um Instagram válido.")
    creator_id = uuid.uuid4().hex
    status = str(payload.get("status", "novo"))
    if status not in STATUSES:
        raise HTTPException(400, "Situação inválida.")
    numbers = {}
    for key in ("valid_depositors", "revenue_cents", "payout_cents"):
        value = payload.get(key, 0)
        if isinstance(value, bool) or not isinstance(value, int) or value < 0 or value > 1_000_000_000:
            raise HTTPException(400, "Valor numérico inválido.")
        numbers[key] = value
    with database() as db:
        db.execute(
            """INSERT INTO creators(id,created_at,source,name,instagram,followers,status,notes,
               valid_depositors,revenue_cents,payout_cents) VALUES(?,?,?,?,?,?,?,?,?,?,?)""",
            (creator_id, now_iso(), "manual", str(payload.get("name", "")).strip()[:120], "@" + instagram,
             str(payload.get("followers", "")).strip()[:80], status, str(payload.get("notes", "")).strip()[:2000],
             numbers["valid_depositors"], numbers["revenue_cents"], numbers["payout_cents"]),
        )
        row = db.execute("SELECT * FROM creators WHERE id=?", (creator_id,)).fetchone()
    return JSONResponse(creator_dict(row), status_code=201)


@app.patch("/api/admin/creators/{creator_id}")
async def update_creator(creator_id: str, request: Request):
    require_write(request)
    payload = await limited_json(request, 8_000)
    allowed_text = {"name": 120, "followers": 80, "notes": 2000}
    allowed_int = {"valid_depositors", "revenue_cents", "payout_cents"}
    updates = {}
    for key, limit in allowed_text.items():
        if key in payload:
            updates[key] = str(payload[key]).strip()[:limit]
    for key in allowed_int:
        if key in payload:
            value = payload[key]
            if isinstance(value, bool) or not isinstance(value, int) or value < 0 or value > 1_000_000_000:
                raise HTTPException(400, "Valor numérico inválido.")
            updates[key] = value
    if "status" in payload:
        if payload["status"] not in STATUSES:
            raise HTTPException(400, "Situação inválida.")
        updates["status"] = payload["status"]
    if not updates:
        raise HTTPException(400, "Nenhuma alteração enviada.")
    columns = ", ".join(f"{key}=?" for key in updates)
    with database() as db:
        cursor = db.execute(f"UPDATE creators SET {columns} WHERE id=?", (*updates.values(), creator_id))
        if cursor.rowcount == 0:
            raise HTTPException(404, "Creator não encontrado.")
        row = db.execute("SELECT * FROM creators WHERE id=?", (creator_id,)).fetchone()
    return creator_dict(row)


